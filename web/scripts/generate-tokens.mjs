import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url)));
const resolve = v => v.replace(/^\{brand\.([\w-]+)\}$/, (_, k) => {
  if (!tokens.brand[k]) throw new Error(`Unknown brand reference ${v}`);
  return tokens.brand[k].value;
});
const theme = name => Object.fromEntries(Object.entries(tokens.color).map(([role, c]) => [role, resolve(c[name])]));
const themes = { dark: theme('dark'), light: theme('light') };

function luminance(hex) { const c = hex.slice(1).match(/../g).map(s => { const x = parseInt(s, 16) / 255; return x <= .04045 ? x / 12.92 : ((x + .055) / 1.055) ** 2.4; }); return c[0] * .2126 + c[1] * .7152 + c[2] * .0722; }
function ratio(a, b) { const x = luminance(a), y = luminance(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); }
for (const [name, t] of Object.entries(themes)) {
  for (const surface of ['bg', 'surface', 'raised']) for (const ink of ['text', 'text-muted', 'brand', 'council', 'danger', 'yes', 'no']) {
    if (ratio(t[ink], t[surface]) < 4.5) throw new Error(`${name}: ${ink} on ${surface} fails AA (${ratio(t[ink], t[surface]).toFixed(2)})`);
  }
  for (const surface of ['bg', 'surface']) if (ratio(t['border-input'], t[surface]) < 3) throw new Error(`${name}: border-input on ${surface} fails 3:1`);
  for (const [fg, bg] of [['on-accent', 'accent'], ['on-council', 'council']]) if (ratio(t[fg], t[bg]) < 4.5) throw new Error(`${name}: ${fg} on ${bg} fails AA`);
  for (const category of ['politics', 'sports', 'crypto', 'economy', 'tech', 'culture', 'world', 'other']) if (ratio(t[`category-${category}-ink`], t[`category-${category}-bg`]) < 4.5) throw new Error(`${name}: category ${category} fails AA`);
}

const vars = (prefix, group) => Object.entries(group).map(([k, v]) => `  --${prefix}${k}: ${v};`);
const fonts = Object.entries(tokens.font).map(([role, f]) => `  --font-${role}-stack: var(${f.variable}), "${f.family}", ${f.fallback};`);
const scale = [
  ...vars('brand-', Object.fromEntries(Object.entries(tokens.brand).map(([k, v]) => [k, v.value]))),
  ...fonts,
  ...vars('fs-', tokens.size), ...vars('lh-', tokens.leading), ...vars('track-', tokens.tracking),
  ...vars('s-', tokens.space), ...vars('r-', tokens.radius), ...vars('control-', tokens.control),
  ...vars('', tokens.layout), ...vars('dur-', tokens.duration), ...vars('ease-', tokens.easing),
  `  --stagger: ${tokens.stagger};`,
];
const colors = t => Object.entries(t).map(([k, v]) => `  --${k}: ${v};`).join('\n');
const css = `/* Generated by npm run tokens from design/tokens.json. Edit the JSON, not this file. */
:root {
  color-scheme: dark;
${colors(themes.dark)}
  --chart-yes: var(--yes);
  --chart-no: var(--no);
${scale.join('\n')}
}
:root[data-theme="light"] {
  color-scheme: light;
${colors(themes.light)}
}
@media (prefers-reduced-motion: reduce) {
  :root { ${Object.keys(tokens.duration).map(k => `--dur-${k}: 0ms;`).join(' ')} --stagger: 0ms; }
}
`;
writeFileSync(new URL('../app/tokens.generated.css', import.meta.url), css);

// DESIGN.md (Google Labs format) carries the tokens agents read; only its front matter is generated.
const yaml = v => /^[\w.-]+$/.test(v) && !/^\d/.test(v) ? v : JSON.stringify(v);
const front = [
  '---',
  'version: alpha',
  'name: Dragons Market',
  `description: ${yaml('Prediction markets on NEAR. Orchid and mint on purple-black; Funnel Display and IBM Plex. Generated from design/tokens.json by npm run tokens.')}`,
  'colors:',
  `  primary: "${themes.dark.brand}"`,
  `  secondary: "${tokens.brand.mint.value}"`,
  ...Object.entries(themes.dark).map(([k, v]) => `  ${k}: "${v}"`),
  ...Object.entries(themes.light).map(([k, v]) => `  ${k}-light: "${v}"`),
  'typography:',
  ...Object.entries(tokens.typeStyles).flatMap(([name, s]) => [
    `  ${name}:`,
    `    fontFamily: ${yaml(tokens.font[s.font].family)}`,
    `    fontSize: ${s.size in tokens.size ? tokens.size[s.size] : s.size}`,
    `    fontWeight: ${s.weight}`,
    `    lineHeight: ${s.leading in tokens.leading ? tokens.leading[s.leading] : s.leading}`,
    ...(s.tracking ? [`    letterSpacing: ${s.tracking in tokens.tracking ? tokens.tracking[s.tracking] : s.tracking}`] : []),
  ]),
  'rounded:',
  ...Object.entries(tokens.radius).map(([k, v]) => `  ${k}: ${v}`),
  'spacing:',
  ...Object.entries(tokens.space).map(([k, v]) => `  "${k}": ${v}`),
  'components:',
  ...Object.entries(tokens.components).flatMap(([name, props]) => [`  ${name}:`, ...Object.entries(props).map(([k, v]) => `    ${k}: ${yaml(v)}`)]),
  '---',
].join('\n');
const designUrl = new URL('../DESIGN.md', import.meta.url);
const body = existsSync(designUrl) ? readFileSync(designUrl, 'utf8').replace(/^---\n[\s\S]*?\n---\n?/, '') : '\n# Dragons Market design\n';
writeFileSync(designUrl, `${front}\n${body.startsWith('\n') ? body : `\n${body}`}`);

console.log('Generated app/tokens.generated.css and DESIGN.md front matter; contrast checks passed in both themes.');
