import test from 'node:test';
import assert from 'node:assert/strict';
import {signBoundary} from '../src/publisher.js';
import {decodeKey} from '../src/auth.js';
import {randomUUID,generateKeyPairSync,createPublicKey,verify} from 'node:crypto';
import {readFile,writeFile,rm} from 'node:fs/promises';
import pg from 'pg';
import {recordEvidence} from '../src/prices.js';
import {migrate} from '../src/migrate.js';
import {readConfig} from '../src/config.js';
import {registerDeployment} from '../src/ingestion/store.js';
import {FixtureSource} from '../src/ingestion/source.js';
import {ingest} from '../src/ingestion/engine.js';
import {exportFeed} from '../src/ingestion/feed.js';
import {enqueue,leaseJob,finishJob,prepareOperation,transitionOperation,boundaries,reserveSigningDecision} from '../src/services.js';

test('jobs, ambiguous sends, operation idempotency, signing conflicts and feed crash recovery',async()=>{
 const url=process.env.TEST_DATABASE_URL;assert.ok(url);const schema=`svc_${randomUUID().replaceAll('-','')}`;
 const admin=new pg.Pool({connectionString:url}),pool=new pg.Pool({connectionString:url,options:`-c search_path=${schema}`});
 const config=readConfig({DATABASE_URL:url,DEPLOYMENT_ID:'services',DEPLOYMENT_START_BLOCK:'100',ROUNDS_CONTRACT_ID:'rounds.fixture.near',VERIFIER_CONTRACT_ID:'verifier.fixture.near',COLLATERAL_TOKEN_ID:'nep141:usdc.fixture.near'});
 const file=`.local/feeds/${schema}.jsonl`;
 try{
 await admin.query(`CREATE SCHEMA ${schema}`);await migrate(pool);await registerDeployment(pool,config);
 const observation={asset:'BTC' as const,source:'binance' as const,quote:'USDC' as const,boundaryNs:'1700000100000000000',sourceTimeNs:'1700000099999000000',retrievedAt:new Date().toISOString(),price:'9007199254740993.01',exactBoundary:true,raw:'public-source-evidence'};
 await recordEvidence(pool,observation);await recordEvidence(pool,observation);
 const evidence=(await pool.query('SELECT price,source_time_ns::text FROM price_evidence')).rows;assert.equal(evidence.length,1);assert.equal(evidence[0].price,observation.price);assert.equal(evidence[0].source_time_ns,observation.sourceTimeNs);
 const due=new Date(Date.now()-1000);
 const id=await enqueue(pool,'services','settle_round','series/0/round/1',{round:'1'},due);
 assert.equal(await enqueue(pool,'services','settle_round','series/0/round/1',{round:'1'},due),id);
 await assert.rejects(enqueue(pool,'services','settle_round','series/0/round/1',{round:'2'},due),/job_idempotency_conflict/);
 const [a,b]=await Promise.all([leaseJob(pool,'services'),leaseJob(pool,'services')]);assert.equal([a,b].filter(Boolean).length,1);
 const job=a??b;await finishJob(pool,job.id,job.lease_token,'unknown');assert.equal(await leaseJob(pool,'services'),null);
 assert.equal((await pool.query('SELECT state FROM backend_jobs WHERE id=$1',[id])).rows[0].state,'reconcile');
 const secondId=await enqueue(pool,'services','reconcile','job2',{},due);const leased=await leaseJob(pool,'services');assert.equal(leased.id,secondId);
 await pool.query("UPDATE backend_jobs SET leased_until=now()-interval '1 second' WHERE id=$1",[secondId]);
 await assert.rejects(finishJob(pool,secondId,leased.lease_token,'done'),/job_lease_lost/);
 assert.equal(await leaseJob(pool,'services'),null);
 const op=await prepareOperation(pool,'services','alice.near','trade','request1',{amount:'9007199254740993'});
 assert.equal((await prepareOperation(pool,'services','alice.near','trade','request1',{amount:'9007199254740993'})).id,op.id);
 await assert.rejects(prepareOperation(pool,'services','alice.near','trade','request1',{amount:'1'}),/operation_idempotency_conflict/);
 await transitionOperation(pool,op.id,'alice.near','prepared','awaiting_signature');
 await assert.rejects(transitionOperation(pool,op.id,'bob.near','awaiting_signature','submitted'),/operation_state_conflict/);
 await transitionOperation(pool,op.id,'alice.near','awaiting_signature','submitted','T'.repeat(32));
 await transitionOperation(pool,op.id,'alice.near','submitted','unknown');
 await assert.rejects(transitionOperation(pool,op.id,'alice.near','unknown','confirmed'),/confirmation_evidence_required/);
 assert.deepEqual(boundaries(600000000000n,0n),{round:'2',startNs:'600000000000',endNs:'900000000000'});
 const signingKey=generateKeyPairSync('ed25519').privateKey;
 const input={contract:'rounds.fixture.near',network:'sandbox',asset:'BTC',momentNs:'600000000000',price:'8000000000000',decimals:8};
 await assert.rejects(signBoundary(pool,'services',input,signingKey,false),/publisher_not_approved/);
 const signed=await signBoundary(pool,'services',input,signingKey,true),signedAgain=await signBoundary(pool,'services',input,signingKey,true);
 assert.deepEqual(signedAgain,signed);const [key,signature]=signed.entry.split('.');
 assert.ok(key&&signature);const publicKey=createPublicKey({key:Buffer.concat([Buffer.from('302a300506032b6570032100','hex'),decodeKey(key)]),format:'der',type:'spki'});
 assert.equal(verify(null,Buffer.from(signed.payload),publicKey,Buffer.from(signature,'hex')),true);
 await assert.rejects(signBoundary(pool,'services',{...input,price:'1'},signingKey,true),/conflicting_boundary_signature/);
 await reserveSigningDecision(pool,'services','publisher','BTC/600','payload');
 await assert.rejects(reserveSigningDecision(pool,'services','publisher','BTC/600','different'),/conflicting_boundary_signature/);
 await ingest(pool,config,new FixtureSource('test/fixtures/blocks.jsonl'));
 assert.equal((await exportFeed(pool,'services',file)).exported,3);
 const before=await readFile(file,'utf8');assert.equal(before.trim().split('\n').length,3);
 // Simulate loss of all DB acknowledgements after bytes were fsynced.
 await pool.query('UPDATE feed_exports SET height=NULL,byte_offset=0');
 assert.equal((await exportFeed(pool,'services',file)).exported,3);
 assert.equal(await readFile(file,'utf8'),before);
 assert.equal((await exportFeed(pool,'services',file)).exported,0);
 await pool.query('UPDATE feed_exports SET height=NULL,byte_offset=0');
 const lines=before.split('\n');await writeFile(file,lines[0]+'\n'+lines[1]!.slice(0,20));
 assert.equal((await exportFeed(pool,'services',file)).exported,3);assert.equal(await readFile(file,'utf8'),before);
 await writeFile(file,before.slice(0,-1));await assert.rejects(exportFeed(pool,'services',file),/feed_truncated/);
 }finally{await rm(file,{force:true});await pool.end();await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);await admin.end();}
});
